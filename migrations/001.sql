CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE TABLE IF NOT EXISTS tenants (id UUID PRIMARY KEY DEFAULT gen_random_uuid(), customer_id VARCHAR(64) UNIQUE NOT NULL, name VARCHAR(200) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS tenant_accounts (tenant_id UUID PRIMARY KEY REFERENCES tenants(id), login_name VARCHAR(200) UNIQUE NOT NULL, password_hash TEXT NOT NULL, last_login_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS tenant_api_keys (id UUID PRIMARY KEY DEFAULT gen_random_uuid(), tenant_id UUID NOT NULL REFERENCES tenants(id), key_hash CHAR(64) UNIQUE NOT NULL, status VARCHAR(16) NOT NULL CHECK(status IN ('active','revoked')), created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by_type VARCHAR(32) NOT NULL, created_by_id VARCHAR(200) NOT NULL, revoked_at TIMESTAMPTZ, revoked_by_type VARCHAR(32), revoked_by_id VARCHAR(200), revoke_reason TEXT);
CREATE TABLE IF NOT EXISTS tenant_mail_configs (tenant_id UUID PRIMARY KEY REFERENCES tenants(id), from_name VARCHAR(100) NOT NULL, subject VARCHAR(200) NOT NULL, html_template TEXT NOT NULL, text_template TEXT NOT NULL, reply_to VARCHAR(254), version BIGINT NOT NULL DEFAULT 1, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS tenant_quotas (tenant_id UUID PRIMARY KEY REFERENCES tenants(id), quota_total BIGINT NOT NULL DEFAULT 0 CHECK(quota_total >= 0), used_count BIGINT NOT NULL DEFAULT 0 CHECK(used_count >= 0), reserved_count BIGINT NOT NULL DEFAULT 0 CHECK(reserved_count >= 0), updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS tenant_quota_adjustments (id BIGSERIAL PRIMARY KEY, tenant_id UUID NOT NULL REFERENCES tenants(id), before_total BIGINT NOT NULL, after_total BIGINT NOT NULL, delta BIGINT NOT NULL CHECK(delta <> 0), reason TEXT, actor_type VARCHAR(32) NOT NULL, actor_id VARCHAR(200) NOT NULL, request_id UUID NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(tenant_id, request_id));
CREATE TABLE IF NOT EXISTS send_requests (id BIGSERIAL PRIMARY KEY, tenant_id UUID NOT NULL REFERENCES tenants(id), request_id UUID NOT NULL, email VARCHAR(254) NOT NULL, reported_client_ip INET, status VARCHAR(16) NOT NULL CHECK(status IN ('pending','accepted','failed','unknown')), smtp_message_id TEXT, smtp_envelope_from VARCHAR(254), smtp_envelope_to VARCHAR(254), smtp_response TEXT, smtp_accepted JSONB, smtp_rejected JSONB, smtp_error_code VARCHAR(64), smtp_error_detail TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), submitted_at TIMESTAMPTZ, completed_at TIMESTAMPTZ, duration_ms INTEGER, updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), resolved_at TIMESTAMPTZ, resolved_by_type VARCHAR(32), resolved_by_id VARCHAR(200), resolution_note TEXT, UNIQUE(tenant_id, request_id));
CREATE TABLE IF NOT EXISTS send_request_contents (send_request_id BIGINT PRIMARY KEY REFERENCES send_requests(id), from_email VARCHAR(254) NOT NULL, from_name VARCHAR(100) NOT NULL, reply_to VARCHAR(254), subject VARCHAR(200) NOT NULL, html_body TEXT NOT NULL, text_body TEXT NOT NULL, config_version BIGINT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS verification_codes (tenant_id UUID NOT NULL REFERENCES tenants(id), email VARCHAR(254) NOT NULL, code CHAR(6) NOT NULL, send_request_id BIGINT NOT NULL REFERENCES send_requests(id), attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts >= 0), expires_at TIMESTAMPTZ NOT NULL, consumed_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(tenant_id, email));
CREATE TABLE IF NOT EXISTS rate_limits (tenant_id UUID NOT NULL REFERENCES tenants(id), limit_type VARCHAR(32) NOT NULL CHECK(limit_type IN ('email_cooldown','email_hour')), email VARCHAR(254) NOT NULL, window_started_at TIMESTAMPTZ NOT NULL, count INTEGER NOT NULL CHECK(count >= 0), expires_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(tenant_id, limit_type, email));
