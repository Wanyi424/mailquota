CREATE OR REPLACE VIEW quota_details AS SELECT tenant_id, created_at AS occurred_at, 'adjustment' AS source_type, id::text AS source_id, delta, reason FROM tenant_quota_adjustments UNION ALL SELECT tenant_id, completed_at AS occurred_at, 'send' AS source_type, id::text AS source_id, -1 AS delta, '邮件发送消耗' AS reason FROM send_requests WHERE status='accepted';
